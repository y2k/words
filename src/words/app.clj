(defn- shuffle [items]
  (effect/dispatch :shuffle-list items))

(defn- question-view [word transcription translations select-answer]
  [:column {}
   [:text {:text (str word " (" transcription ")")}]
   (concat
    [:row {}
     [:button {:text "?"
               :compact true
               :description "Не знаю"
               :onclick (fn [] (select-answer nil))}]]
    (map
     (fn [translation]
       [:button {:text translation
                 :onclick (fn [] (select-answer translation))}])
     translations))])

(defn- question-data [words]
  [(get (get words 0) 0)
   (get (get words 0) 2)
   (map (fn [index]
          (get (get words index) 1))
        [0 1 2 3 4])])

(defn- create-question [dictionary]
  (effect/next
   (shuffle dictionary)
   (fn [entries]
     (let [[word transcription translations] (question-data entries)
           correct-answer (get translations 0)]
       (effect/next
        (shuffle translations)
        (fn [answers]
          (update-ui
           (question-view
            word
            transcription
            answers
            (fn [answer]
              (if (= answer correct-answer)
                (create-question dictionary)
                (effect/next
                 (update-ui
                  [:text {:text (str "Правильный ответ: " correct-answer)}])
                 (fn [_view] (create-question dictionary)))))))))))))

(defn- start [dictionary]
  (effect/next
   (effect/dispatch :clear-ui nil)
   (fn [_view] (create-question dictionary))))

(defn main []
  (update-ui
   [:column {}
    [:row {}
     [:button {:text "Сербский"
               :onclick (fn [] (start (SERBIAN-WORDS)))}]
     [:button {:text "Французский"
               :onclick (fn [] (start (FRENCH-WORDS)))}]]]))
